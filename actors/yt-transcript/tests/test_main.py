"""Tests for main(): what happens to links when the run stops early.

The promise on the store page is "every link you send becomes a row, and the
run never goes silent". These tests hold the code to it: a spending cap, a
maxVideos cut and a plain failure all have to leave a row behind.

No network and no platform: the Apify SDK is replaced by a stand-in instance,
and fetch() is replaced by a stub.

Run directly:  python tests/test_main.py
"""
import asyncio
import os
import sys
import types

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
sys.path.insert(0, ROOT)

VIDS = ["dQw4w9WgXcQ", "jNQXAC9IVRw", "kJQP7kiw5Fk", "9bZkp7q19f0"]


class _Log:
    def info(self, *a, **k):
        pass

    def warning(self, *a, **k):
        pass


class _Charge:
    def __init__(self, reached):
        self.event_charge_limit_reached = reached


class FakeActor:
    def __init__(self):
        self.rows = []
        self.values = {}
        self.input = {}
        self.charges = 0
        self.limit_after = None
        self.log = _Log()

    async def __aenter__(self):
        return self

    async def __aexit__(self, *exc):
        return False

    async def get_input(self):
        return self.input

    async def push_data(self, row):
        self.rows.append(dict(row))

    async def set_value(self, key, value, *a, **k):
        self.values[key] = value

    async def open_key_value_store(self, name=None):
        return None

    async def create_proxy_configuration(self, *a, **k):
        return None

    async def charge(self, event_name=None):
        self.charges += 1
        reached = self.limit_after is not None and self.charges >= self.limit_after
        return _Charge(reached)


FAKE = FakeActor()
_apify = types.ModuleType("apify")
_apify.Actor = FAKE
sys.modules["apify"] = _apify

from src import main as m  # noqa: E402


def _ok(item):
    return {
        "ok": True, "url": item, "videoId": m.video_id(item), "title": "t", "channel": "c",
        "channelId": "cc", "durationSeconds": 10, "viewCount": 5, "language": "en",
        "languageFallback": False, "isAutoGenerated": False, "availableLanguages": ["en"],
        "segments": [{"start": 0.0, "duration": 1.0, "text": "hi"}], "transcript": "hi",
    }


def _run(inp, limit_after=None, fetch=None):
    FAKE.__init__()
    FAKE.input = inp
    FAKE.limit_after = limit_after
    m.fetch = fetch or (lambda item, *a, **k: _ok(item))
    asyncio.run(m.main())
    return FAKE


def _urls(n=4):
    return [f"https://www.youtube.com/watch?v={v}" for v in VIDS[:n]]


def test_spending_cap_leaves_a_row_for_every_link():
    fake = _run({"videoUrls": _urls(4), "cacheMinutes": 0}, limit_after=1)
    status = [row["status"] for row in fake.rows]
    assert status.count("SUCCESS") == 1, status
    assert status.count("NOT_CHECKED_CAP") == 3, status
    assert len(fake.rows) == 4, fake.rows
    summary = fake.values["SUMMARY"]
    assert summary["requested"] == 4
    assert summary["delivered"] == 1
    assert summary["notChecked"] == 3
    assert summary["stopped"] is True
    assert summary["stopReason"] == "spending-cap"


def test_max_videos_cut_is_reported_not_dropped():
    fake = _run({"videoUrls": _urls(4), "maxVideos": 2, "cacheMinutes": 0})
    status = [row["status"] for row in fake.rows]
    assert status.count("SUCCESS") == 2, status
    assert status.count("NOT_CHECKED_LIMIT") == 2, status
    summary = fake.values["SUMMARY"]
    assert summary["requested"] == 4
    assert summary["overMaxVideos"] == 2
    assert summary["delivered"] == 2
    assert summary["notChecked"] == 2
    assert summary["stopReason"] == "max-videos"


def test_every_reason_is_written():
    fake = _run({"videoUrls": _urls(2) + ["not a link"], "maxVideos": 5, "cacheMinutes": 0})
    bad = [row for row in fake.rows if row.get("status") != "SUCCESS"]
    assert len(bad) == 1 and bad[0]["error"] == "BAD_URL", fake.rows
    assert bad[0]["reason"]


def test_clean_run_has_no_not_checked_rows():
    fake = _run({"videoUrls": _urls(3), "cacheMinutes": 0})
    assert [row["status"] for row in fake.rows] == ["SUCCESS"] * 3, fake.rows
    summary = fake.values["SUMMARY"]
    assert summary["delivered"] == 3 and summary["notChecked"] == 0
    assert summary["stopped"] is False and summary["stopReason"] is None


def test_summary_always_written():
    fake = _run({"videoUrls": _urls(1), "cacheMinutes": 0})
    assert "SUMMARY" in fake.values
    assert fake.values["SUMMARY"]["delivered"] == 1


def run_all():
    tests = [(name, fn) for name, fn in sorted(globals().items()) if name.startswith("test_") and callable(fn)]
    failed = []
    for name, fn in tests:
        try:
            fn()
            print(f"ok   {name}")
        except Exception as exc:
            failed.append((name, exc))
            print(f"FAIL {name}: {type(exc).__name__}: {exc}")
    print(f"\n{len(tests) - len(failed)}/{len(tests)} passed")
    return failed


if __name__ == "__main__":
    sys.exit(1 if run_all() else 0)
